export function normalizeLang(lang) {
  const l = String(lang || DEFAULT_LANG).toLowerCase().slice(0, 2);
  return SUPPORTED.includes(l) ? l : DEFAULT_LANG;
}

export function createTranslator(lang) {
  const l = normalizeLang(lang);
  const bag = STRINGS[l] || STRINGS[DEFAULT_LANG];
  function t(key, vars) {
    let s = bag[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
    if (vars && typeof vars === 'object') {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
      }
    }
    return s;
  }
  /** Translate free-form German UI labels (menus, titles) when lang is en. */
  function tx(text) {
    if (text == null || text === '') return text;
    if (l === 'de') return text;
    const s = String(text);
    if (DE_TO_EN[s]) return DE_TO_EN[s];
    // Multi-word: replace known tokens, keep rest
    let out = s;
    for (const [de, en] of Object.entries(DE_TO_EN)) {
      if (de.length < 3) continue;
      if (out.includes(de)) out = out.split(de).join(en);
    }
    return out;
  }
  return { lang: l, t, tx, strings: bag };
}

/** Parse Cookie header without requiring cookie-parser. */
export function langFromRequest(req) {
  if (req?.session?.lang) return normalizeLang(req.session.lang);
  if (req?.cookies?.lang) return normalizeLang(req.cookies.lang);
  const raw = req?.headers?.cookie || '';
  const m = /(?:^|;\s*)lang=([a-zA-Z-]+)/.exec(raw);
  if (m) return normalizeLang(m[1]);
  return DEFAULT_LANG;
}
